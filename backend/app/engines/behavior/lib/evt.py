"""Extreme-value and point-process tests (B12 beacon, B13 budget, B24 tails).

STATUS: implemented. Signatures are frozen (docs/lib3/helpers_api.md); where
the maths departs from the original stub (null-table grids, window-corrected
Z^2, Davies trials bound) it is marked DEVIATION below, with the measurement
that forced it, and listed in helpers_api.md.

Why PWM for the GPD: with 10-30 exceedances maximum likelihood is unstable
and slow; probability-weighted moments (Hosking & Wallis 1987) are closed
form, O(n log n), and well behaved for xi in [-0.5, 0.5], which is the range
we clip to anyway.

Why a Gamma renewal LRT for beacons: a C2 implant with +-30% jitter is a
renewal process whose intervals are Gamma-like with shape kappa >> 1, while
human / Poisson traffic has kappa <= 1. Phase-based tests (Rayleigh,
Lomb-Scargle) lose coherence under renewal jitter (measured Rayleigh median
p = 0.14 at n = 40). The chi2_1 asymptotic of the LRT is 2-5x
anti-conservative at n <= 40, hence the tabulated finite-n null.

Why the null table is *exact* rather than Monte-Carlo: the LR depends on
the intervals only through s = ln(mean x) - mean(ln x) and is monotone in s,
so P0(LR >= c) = P0(s <= s_c). Under i.i.d. Exp intervals x / sum(x) is
Dirichlet(1, ..., 1), which gives the Mellin transform of T = n s in closed
form: E[exp(u T)] = n^(-n u) Gamma(n) Gamma(1 - u)^n / Gamma(n (1 - u)).
Inverting it on a Bromwich line through the saddlepoint (trapezoid rule,
spectrally accurate) gives P0(T <= t) to ~1e-12 in log p at any depth,
where 1e5 simulations resolve nothing below ~1e-4. scripts/gen_beacon_null.py
builds the constants that way and checks them against >= 2e4 Monte-Carlo
draws per n (bulk) and Dirichlet-tilted importance sampling (tail).

Why the Z^2 scan is window-corrected and uses an upcrossing bound: measured
on Poisson event times, the stub's Bonferroni n_eff * chi2.sf was 2-5x
anti-conservative at alpha <= 1e-2 (an oversampled scan of a chi2 process
has ~sqrt(z/2) more effective trials than independent Fourier frequencies,
Davies 1987), and 12x at n = 256 because a non-integer number of cycles
over the observation window biases Z^2 upwards at the lowest frequencies.
Subtracting the window's expected phasor and using the Davies bound gives
realised / nominal 0.2-0.9 for n = 12..256 at 1e-1..1e-3. The first and
last events define the window, so they sit at phases 0 and 2 pi T/P by
construction and only the n - 2 interior times are uniform: the expected
phasor is 1 + e^(i theta) + (n - 2) w, not n w (the latter left a mean of up
to 2 per harmonic, which made the union bound 1.25-1.7x anti-conservative
at n = 20..40). With that, min(Davies, L chi2.sf) realises 0.15-1.0x
nominal at 1e-1..1e-3 for n = 12..256 (2e4 Poisson streams per case).
"""
